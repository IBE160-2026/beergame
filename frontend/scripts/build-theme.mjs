// Generates src/theme/theme.css from src/theme/tokens.json, the theme's one source.
// tokens.json is a copy of DESIGN.md's front matter (colors, typography, rounded, spacing).
// Run with `npm run theme` after changing tokens.json; a Vitest test fails on drift.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOKENS_PATH = path.join(here, "..", "src", "theme", "tokens.json");
export const THEME_PATH = path.join(here, "..", "src", "theme", "theme.css");

export const FONT_STACK = '"Source Sans 3", "Source Sans Pro", "Segoe UI", Arial, sans-serif';

/** Roles that keep proportional figures; every other text uses lining tabular figures. */
export const PROPORTIONAL_ROLES = ["figure-hero", "figure-amplification"];

/** "48px" -> "3rem"; other values (unitless, em) unchanged. Text grows with browser zoom. */
export function pxToRem(value) {
  const match = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value));
  if (!match) return String(value);
  const rem = Number(match[1]) / 16;
  return `${Number(rem.toFixed(6))}rem`;
}

export function renderTheme(tokens) {
  const lines = [
    "/* Generated by scripts/build-theme.mjs from src/theme/tokens.json. Do not edit by hand. */",
    "/* `static` emits every token on :root, so hand-made SVG charts can read var(--color-*). */",
    "@theme static {",
    "  --color-*: initial;",
    "  --text-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --inset-shadow-*: initial;",
    "  --drop-shadow-*: initial;",
    "  --text-shadow-*: initial;",
    "  --tracking-*: initial;",
    "",
    `  --font-sans: ${FONT_STACK};`,
    "",
  ];
  for (const [name, value] of Object.entries(tokens.colors)) {
    lines.push(`  --color-${name}: ${value};`);
  }
  lines.push("");
  for (const [role, spec] of Object.entries(tokens.typography)) {
    lines.push(`  --text-${role}: ${pxToRem(spec.fontSize)};`);
    if (spec.lineHeight !== undefined) {
      lines.push(`  --text-${role}--line-height: ${pxToRem(spec.lineHeight)};`);
    }
    lines.push(`  --text-${role}--font-weight: ${spec.fontWeight};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(tokens.rounded)) {
    lines.push(`  --radius-${name}: ${value};`);
  }
  lines.push("");
  for (const [name, value] of Object.entries(tokens.spacing)) {
    lines.push(`  --spacing-${name}: ${value};`);
  }
  lines.push("}", "");
  lines.push(
    "/* Proportional figures only in the largest single numbers (DESIGN.md → Typography). */",
    `${PROPORTIONAL_ROLES.map((r) => `.text-${r}`).join(",\n")} {`,
    "  font-variant-numeric: lining-nums proportional-nums;",
    "}",
    "",
  );
  return lines.join("\n");
}

export function readTokens() {
  return JSON.parse(fs.readFileSync(TOKENS_PATH, "utf8"));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(THEME_PATH, renderTheme(readTokens()));
  console.log(`wrote ${path.relative(process.cwd(), THEME_PATH)}`);
}
